const DICT: Record<Lang, Record<I18nKey, string>> = { vi: VI, en: EN };

export function getStoredLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "vi";
  } catch {
    return "vi";
  }
}

function applyLang(lang: Lang): void {
  document.documentElement.lang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Ignore storage quota / privacy mode errors
  }
  window.dispatchEvent(new CustomEvent<Lang>(LANG_EVENT, { detail: lang }));
}

export function translate(
  lang: Lang,
  key: I18nKey,
  vars?: Record<string, string | number>,
): string {
  const template = DICT[lang][key] ?? DICT.vi[key];
  if (!vars) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (full, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : full,
  );
}

export function tNow(key: I18nKey, vars?: Record<string, string | number>): string {
  return translate(getStoredLang(), key, vars);
}

export function useLang() {
  const [lang, setLangState] = useState<Lang>(() => getStoredLang());

  useEffect(() => {
    const onCustom = (e: Event) => {
      const next = (e as CustomEvent<Lang>).detail;
      if (next === "vi" || next === "en") setLangState(next);
    };
    const onStorage = (e: StorageEvent) => {
      if (e.key === STORAGE_KEY) {
        const next = getStoredLang();
        document.documentElement.lang = next;
        setLangState(next);
      }
    };
    window.addEventListener(LANG_EVENT, onCustom);
    window.addEventListener("storage", onStorage);
    return () => {
      window.removeEventListener(LANG_EVENT, onCustom);
      window.removeEventListener("storage", onStorage);
    };
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    applyLang(next);
  }, []);

  const toggleLang = useCallback(() => {
    setLangState((cur) => {
      const next: Lang = cur === "vi" ? "en" : "vi";
      applyLang(next);
      return next;
    });
  }, []);

  const t = useCallback(
    (key: I18nKey, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang],
  );

  return { lang, setLang, toggleLang, t };
}
